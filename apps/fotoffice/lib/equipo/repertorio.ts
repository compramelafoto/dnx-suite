import type { MomentoPieza, Ocasion, Parte } from "./mensajes";

/**
 * El repertorio inicial de mensajes. Módulo PURO.
 *
 * Se copia a la base la primera vez que se necesita (cada pieza con su `clave` estable), y desde
 * ahí el dueño lo edita, apaga o amplía en Equipo → Mensajes. Las frases evitan los adjetivos
 * con género ("cansada", "lista") para que sirvan a cualquier persona del equipo.
 *
 * Variables: {nombre}, {dia} (el día de la semana: "lunes"), {ventas} ("12 ventas"; la pieza
 * sólo se usa si hubo alguna) y {feriado} (el nombre del feriado).
 */

export type PiezaInicial = {
  clave: string;
  momento: MomentoPieza;
  parte: Parte;
  ocasion: Ocasion | null;
  texto: string;
};

function grupo(prefijo: string, momento: MomentoPieza, parte: Parte, ocasion: Ocasion | null, textos: string[]): PiezaInicial[] {
  return textos.map((texto, i) => ({
    clave: `${prefijo}-${String(i + 1).padStart(2, "0")}`,
    momento,
    parte,
    ocasion,
    texto,
  }));
}

