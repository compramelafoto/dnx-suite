export const LEVELS = [
  { id: "inicial", title: "Nivel Inicial", description: "Los fundamentos: exposición, movimiento, enfoque, color y composición." },
  { id: "avanzado", title: "Nivel Avanzado", description: "Control fino de la luz: modos, medición, horas mágicas, noche y estudio." },
] as const;

export function lessonById(id: string): Lesson | null {
  return LESSONS.find((l) => l.id === id) ?? null;
}

export function lessonsOfLevel(level: Lesson["level"]): Lesson[] {
  return LESSONS.filter((l) => l.level === level).sort((a, b) => a.number - b.number);
}

/** La lección que sigue (la próxima del mismo nivel, o la primera del siguiente). */
export function nextLesson(id: string): Lesson | null {
  const i = LESSONS.findIndex((l) => l.id === id);
  return i >= 0 && i < LESSONS.length - 1 ? LESSONS[i + 1] : null;
}

/** Dirección del simulador preparado para la tarea. */
export function lessonTaskHref(id: string, simulator: "calle" | "estudio"): string {
  return simulator === "calle" ? `/camofduty/simulador?leccion=${id}` : `/camofduty/estudio?leccion=${id}`;
}
